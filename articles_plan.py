def get_article_by_id(article_id):
    """根据ID获取文章配置"""
    for article in ARTICLES:
        if article["id"] == article_id:
            return article
    return None

def get_unpublished_articles(published_ids):
    """获取未发布的文章列表"""
    return [a for a in ARTICLES if a["id"] not in published_ids]

def get_total_count():
    """获取文章总数"""
    return len(ARTICLES)
